/**
 * Посилання з листа (відновлення пароля, підтвердження пошти) або вхід через Google не вдався —
 * Supabase повертає на сайт з помилкою в адресі (?error=…#error_code=…). Без цього сайт мовчки
 * показував звичайну сторінку, а помилка лишалась в адресі. Так само — з посиланням, яке може
 * обміняти лише Android-застосунок (?code=).
 */

/** Текст для людини або null, якщо з адреси входу немає що пояснювати. */
export function linkError(href: string): string | null {
  let u: URL;
  try {
    u = new URL(href);
  } catch {
    return null;
  }
  const hash = new URLSearchParams(u.hash.replace(/^#/, ''));
  const get = (k: string) => hash.get(k) ?? u.searchParams.get(k);
  // ?code= (PKCE) сайт не створює ніколи (тут implicit) — це лист, запрошений в Android-застосунку до v21.
  // Обміняти код може лише той застосунок, тож пояснюємо, що робити далі, замість мовчання.
  if (u.searchParams.get('code') && !get('access_token') && !get('error') && !get('error_code')) {
    return 'Це посилання з листа, який просили в застосунку «Дванадцятка». '
      + 'Якщо ти підтверджував пошту — її вже підтверджено, увійди в застосунку ✅ '
      + 'Якщо хотів новий пароль — натисни тут «Забули пароль?» і відкрий новий лист 📬';
  }
  if (!get('error') && !get('error_code') && !get('error_description')) return null;
  if (get('error_code') === 'otp_expired') {
    return 'Посилання з листа вже використане або застаріло — воно спрацьовує лише один раз. '
      + 'Якщо ти вже увійшов — усе гаразд. Якщо ні — попроси новий лист 📬';
  }
  return 'Не вдалося увійти за цим посиланням. Спробуй ще раз 🙏';
}
