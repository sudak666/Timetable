const shuffle = <T,>(a: T[]): T[] => {
  const r = [...a];
  for (let i = r.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [r[i], r[j]] = [r[j]!, r[i]!]; }
  return r;
};

interface Q { q: string; right: string; opts: string[] }
let qs: Q[] = [], qi = 0, ok = 0, picked: string | null = null;

export function quizStart(): void {
  qs = shuffle(QZ).slice(0, 3).map(([q, a]) => ({ q, right: a[0]!, opts: shuffle(a) }));
  qi = ok = 0;
  picked = null;
  set({});
}

function answer(o: string, e: MouseEvent) {
  if (picked) return;
  picked = o;
  if (o === qs[qi]!.right) { ok++; addStar(e.clientX, e.clientY); }
  set({});
  setTimeout(() => { qi++; picked = null; set({}); }, 900);
}

export function quizView(): TemplateResult {
  if (!qs.length) quizStart();
  if (qi >= qs.length)
    return html`<p class="q" aria-live="polite">${emo(ok === 3 ? '🏆 Ідеально!' : ok ? '👍 Непогано!' : '💪 Наступного разу вийде!')} ${ok}/3 — +${ok} ${emo('⭐')}</p><button type="button" @click=${quizStart}>Ще раз</button>`;
  const q = qs[qi]!;
  return html`<p class="msg" style="margin:0">Питання ${qi + 1} з 3</p><p class="q" id="qz-q">${q.q}</p>
    <div class="ans" role="group" aria-labelledby="qz-q">${q.opts.map((o) => html`<button type="button" ?disabled=${!!picked}
      class=${classMap({ ok: !!picked && o === q.right, no: picked === o && o !== q.right })}
      @click=${(e: MouseEvent) => answer(o, e)}>${o}</button>`)}</div>`;
}
